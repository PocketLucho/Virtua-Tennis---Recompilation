#!/usr/bin/env python3
"""Split an AOT block dump (VNBA_AOT_DUMP output) into compilable translation units.

usage: aot_split.py <dump.cpp> [more dumps...] -o <outdir> [-n units]
Blocks are de-duplicated by (vaddr, fpu); if the same block appears with a different
code hash, both are dropped and reported (code at that address is not stable).
"""
import argparse, os, re, sys

ap = argparse.ArgumentParser()
ap.add_argument("dumps", nargs="+")
ap.add_argument("-o", "--out", required=True)
ap.add_argument("-n", "--units", type=int, default=16)
ap.add_argument("--exclude-bios", action="store_true", help="drop blocks below 0x00200000 (physical)")
a = ap.parse_args()

hdr = re.compile(r"^//@BLOCK ([0-9A-F]{8}) ([0-9A-F]{6}) ([0-9A-F]{8}) (\d+) (\S+)$")
blocks = {}
for path in a.dumps:
    cur = None
    with open(path) as f:
        for line in f:
            m = hdr.match(line.rstrip("\n"))
            if m:
                vaddr, fpu, h, size, name = int(m[1], 16), int(m[2], 16), int(m[3], 16), int(m[4]), m[5]
                k = (vaddr, fpu, h)
                if not name.endswith(f"_{h:08X}"):
                    name = f"{name}_{h:08X}"
                cur = None if k in blocks else {"vaddr": vaddr, "fpu": fpu, "hash": h, "size": size, "name": name, "code": [], "orig": m[5]}
                if cur is not None:
                    blocks[k] = cur
                continue
            if line.startswith("//!"):
                cur = None
                continue
            if cur is not None:
                cur["code"].append(line.replace("static void " + cur["orig"], "void " + cur["name"], 1)
                                   .replace("\tUpdateINTC();", "\taot_update_intc();"))
if a.exclude_bios:
    blocks = {k: v for k, v in blocks.items() if (k[0] & 0x1FFFFFFF) >= 0x00200000}
conflicts = set()

os.makedirs(a.out, exist_ok=True)
for fn in os.listdir(a.out):
    if fn.startswith("aot_gen_") and fn.endswith(".cpp"):
        os.remove(os.path.join(a.out, fn))
items = sorted(blocks.values(), key=lambda b: (b["vaddr"], b["fpu"]))
per = (len(items) + a.units - 1) // a.units
for u in range(a.units):
    chunk = items[u * per:(u + 1) * per]
    with open(os.path.join(a.out, f"aot_gen_{u:02d}.cpp"), "w") as f:
        f.write('// Generated by aot_split.py -- do not edit\n#include "hw/sh4/aot/aot_prelude.h"\n\n')
        for b in chunk:
            f.writelines(b["code"])
with open(os.path.join(a.out, "aot_gen_table.cpp"), "w") as f:
    f.write('// Generated by aot_split.py -- do not edit\n#include "hw/sh4/aot/aot_runtime.h"\n\n')
    for b in items:
        f.write(f"void {b['name']}(Sh4Context *);\n")
    f.write("\nconst AotBlockEntry aot_blocks[] = {\n")
    for b in items:
        f.write(f"\t{{ 0x{b['vaddr']:08X}u, 0x{b['fpu']:06X}u, 0x{b['hash']:08X}u, {b['size']}u, {b['name']} }},\n")
    f.write("};\nconst size_t aot_block_count = sizeof(aot_blocks) / sizeof(aot_blocks[0]);\n")
print(f"{len(items)} blocks in {a.units} units, {len(set((b["vaddr"], b["fpu"]) for b in blocks.values()))} distinct addresses", file=sys.stderr)
